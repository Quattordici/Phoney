    /// <summary>Whether <see cref="string.Normalize(NormalizationForm)"/> decomposes non-ASCII text (false with invariant globalization).</summary>
    public static bool PlatformNormalizes => Platform.Normalizes;

    /// <summary>The compatibility decomposition of <paramref name="text"/>.</summary>
    public static string FormKD(string text) => Platform.Normalizes ? text.Normalize(NormalizationForm.FormKD) : WithTable(text);

    /// <summary>The compatibility decomposition of <paramref name="text"/> from the table (and the Hangul formula), whatever the platform.</summary>
    public static string WithTable(string text)
    {
        var sb = new StringBuilder(text.Length + 8);
        foreach (var rune in text.EnumerateRunes())
        {
            var value = rune.Value;
            if (value is >= HangulFirst and <= HangulLast)
            {
                // Unicode 3.12: a syllable is a leading consonant, a vowel and an optional trailing consonant.
                var index = value - HangulFirst;
                sb.Append((char)(0x1100 + (index / 588)));
                sb.Append((char)(0x1161 + (index % 588 / 28)));
                if (index % 28 != 0)
                    sb.Append((char)(0x11A7 + (index % 28)));
            }
            else if (value >= 0xA0 && Table.Map.TryGetValue(value, out var decomposed))
            {
                sb.Append(decomposed);
            }
            else
            {
                sb.Append(rune.ToString());
            }
        }

        return sb.ToString();
    }

    /// <summary>The table's entries in order, for tests.</summary>
    internal static List<(string Text, string Decomposed)> TableEntries()
    {
        var entries = new List<(string, string)>(2048);
        foreach (var pair in Pairs.Split('§', StringSplitOptions.RemoveEmptyEntries))
        {
            var keyLength = char.IsHighSurrogate(pair[0]) ? 2 : 1;
            entries.Add((pair[..keyLength], pair[keyLength..]));
        }

        return entries;
    }

    private const int HangulFirst = 0xAC00;
    private const int HangulLast = 0xD7A3;

    private static class Platform
    {
        public static readonly bool Normalizes = "Å".Normalize(NormalizationForm.FormD).Length == 2;
    }

    private static class Table
    {
        public static readonly Dictionary<int, string> Map = Parse();

        private static Dictionary<int, string> Parse()
        {
            var map = new Dictionary<int, string>(2048);
            foreach (var (text, decomposed) in TableEntries())
                map.Add(char.ConvertToUtf32(text, 0), decomposed);
            return map;
        }
    }
